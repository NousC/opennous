#!/usr/bin/env node
// Sync the context-graph substrate → the open-source mirror repo.
//
// opennous is the source of truth; this assembles the OSS repo's packages/core from the closed,
// product-import-free substrate set defined in context-graph.paths.json (substrate.clean). It does
// NOT create an in-opennous package (that would force every Dockerfile + the lockfile + build order
// to change; a mistake breaks every deploy).
//
// Usage: node scripts/sync-context-graph.mjs [--out <dir>]
//   --out  target OSS repo checkout (default: $CONTEXT_GRAPH_DIR or ../context-graph)

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, cpSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const argOut = (() => { const i = process.argv.indexOf('--out'); return i > -1 ? process.argv[i + 1] : null; })();
const OUT = argOut || process.env.CONTEXT_GRAPH_DIR || join(ROOT, '..', 'context-graph');

const manifest = JSON.parse(readFileSync(join(ROOT, 'context-graph.paths.json'), 'utf8'));
const files = manifest.substrate.clean;               // the closed 18-file substrate set
const SRC_PREFIX = 'packages/core/src/';

if (!existsSync(OUT)) { console.error(`OSS repo dir not found: ${OUT}`); process.exit(1); }
console.log(`Syncing ${files.length} substrate files → ${OUT}/packages/core\n`);

// Fresh src tree (don't leave stale files from a previous run).
const coreSrc = join(OUT, 'packages/core/src');
rmSync(coreSrc, { recursive: true, force: true });
mkdirSync(coreSrc, { recursive: true });

const exportsList = [];
for (const f of files) {
  if (!f.startsWith(SRC_PREFIX)) { console.error(`unexpected path (not under ${SRC_PREFIX}): ${f}`); process.exit(1); }
  const rel = f.slice(SRC_PREFIX.length);             // e.g. db/canonicalAxes.ts
  const src = join(ROOT, f);
  const dst = join(coreSrc, rel);
  mkdirSync(dirname(dst), { recursive: true });
  cpSync(src, dst);
  exportsList.push('./' + rel.replace(/\.ts$/, '.js'));
  console.log(`  + ${rel}`);
}

// Generated barrel — exports ONLY the substrate (opennous's index also exports product modules).
const index = [
  '// GENERATED by scripts/sync-context-graph.mjs — do not edit here; edit in opennous.',
  '// The public API of the open-source context graph (substrate only).',
  '',
  ...exportsList.sort().map(p => `export * from '${p}';`),
  '',
].join('\n');
writeFileSync(join(coreSrc, 'index.ts'), index);

// Standalone package.json + tsconfig (the OSS repo has no shared base to extend).
const pkg = {
  name: '@contextgraph/core',
  version: '0.1.0',
  description: 'The context graph substrate: identity resolution, observations, claims, reconciliation, governance.',
  type: 'module',
  main: './dist/index.js',
  exports: { '.': './dist/index.js' },
  scripts: { build: 'tsc', typecheck: 'tsc --noEmit' },
  dependencies: { '@anthropic-ai/sdk': '^0.71.0', '@supabase/supabase-js': '^2.44.0' },
  devDependencies: { '@types/node': '^22.19.18', typescript: '^5.4.0' },
};
writeFileSync(join(OUT, 'packages/core/package.json'), JSON.stringify(pkg, null, 2) + '\n');

const tsconfig = {
  compilerOptions: {
    target: 'ES2022',
    module: 'NodeNext',
    moduleResolution: 'NodeNext',
    outDir: './dist',
    rootDir: './src',
    strict: true,
    skipLibCheck: true,
    esModuleInterop: true,
    resolveJsonModule: true,
    declaration: true,
    allowJs: true,
  },
  include: ['src'],
};
writeFileSync(join(OUT, 'packages/core/tsconfig.json'), JSON.stringify(tsconfig, null, 2) + '\n');

console.log(`\n✅ Wrote ${files.length} files + index.ts + package.json + tsconfig.json to ${relative(process.cwd(), join(OUT, 'packages/core'))}`);
console.log('Next: cd packages/core && pnpm install && pnpm build');
